@dataclass(frozen=True)
class HorizonSignal:
    """Quantitative signal generated within an individual alpha horizon."""

    horizon: AlphaHorizon
    symbol: str
    timestamp_ms: int
    direction: float  # [-1.0 (strong short), +1.0 (strong long)]
    conviction: float  # [0.0 (no conviction), 1.0 (maximum conviction)]
    raw_score: float
    features: dict[str, float] = field(default_factory=dict)

    def to_dict(self) -> dict[str, Any]:
        return {
            "horizon": str(self.horizon),
            "symbol": self.symbol,
            "timestamp_ms": self.timestamp_ms,
            "direction": round(self.direction, 4),
            "conviction": round(self.conviction, 4),
            "raw_score": round(self.raw_score, 4),
            "features": {k: round(v, 4) for k, v in self.features.items()},
        }


@dataclass(frozen=True)
class EnsembleWeights:
    """Dynamic weight distribution across the three alpha horizons."""

    micro_weight: float  # [0.0, 1.0]
    short_weight: float  # [0.0, 1.0]
    medium_weight: float  # [0.0, 1.0]
    regime: MarketRegime
    regime_confidence: float = 1.0

    @property
    def weights_sum(self) -> float:
        return round(self.micro_weight + self.short_weight + self.medium_weight, 4)

    def to_dict(self) -> dict[str, Any]:
        return {
            "micro_weight": round(self.micro_weight, 4),
            "short_weight": round(self.short_weight, 4),
            "medium_weight": round(self.medium_weight, 4),
            "weights_sum": self.weights_sum,
            "regime": str(self.regime),
            "regime_confidence": round(self.regime_confidence, 4),
        }


