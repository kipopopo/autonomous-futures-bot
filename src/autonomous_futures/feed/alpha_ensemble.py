class MultiHorizonAlphaExtractor:
    """Extracts typed quantitative signals across micro, short, and medium horizons."""

    def extract_micro_signal(
        self,
        symbol: str,
        timestamp_ms: int,
        order_flow_imbalance: float,  # OFI [-1.0, 1.0]
        hawkes_hazard: float,  # rho [0.0, 2.0]
        quote_pressure: float,  # [-1.0, 1.0]
    ) -> HorizonSignal:
        """Extract micro-horizon alpha (1s-5s) based on OFI and Hawkes jump intensity."""
        # Clean inputs
        ofi = max(-1.0, min(1.0, order_flow_imbalance))
        qp = max(-1.0, min(1.0, quote_pressure))
        rho = max(0.0, min(2.0, hawkes_hazard))

        # Micro direction is primarily OFI with quote pressure refinement
        raw_direction = 0.65 * ofi + 0.35 * qp
        direction = max(-1.0, min(1.0, raw_direction))

        # Conviction scales with magnitude of OFI and is suppressed if Hawkes hazard spikes
        hazard_damping = max(0.0, min(1.0, 1.0 - max(0.0, rho - 0.70) / 0.50))
        raw_conviction = (0.70 * abs(ofi) + 0.30 * abs(qp)) * hazard_damping
        conviction = max(0.0, min(1.0, raw_conviction))

        features = {
            "ofi": ofi,
            "hawkes_hazard": rho,
            "quote_pressure": qp,
            "hazard_damping": hazard_damping,
        }
        return HorizonSignal(
            horizon=AlphaHorizon.MICRO_1S_5S,
            symbol=symbol,
            timestamp_ms=timestamp_ms,
            direction=direction,
            conviction=conviction,
            raw_score=raw_direction,
            features=features,
        )

    def extract_short_signal(
        self,
        symbol: str,
        timestamp_ms: int,
        vwap_deviation_bps: float,  # Deviation from short-term VWAP [-50.0, 50.0] bps
        short_momentum_pct: float,  # 5-minute price momentum [-2.0, 2.0] %
        volatility_ratio: float,  # Current vol / baseline vol [0.2, 5.0]
    ) -> HorizonSignal:
        """Extract short-horizon alpha (1m-5m) based on VWAP deviation and momentum."""
        v_dev = max(-50.0, min(50.0, vwap_deviation_bps))
        mom = max(-2.0, min(2.0, short_momentum_pct))
        vol_ratio = max(0.2, min(5.0, volatility_ratio))

        # Normalized direction: momentum direction with mean-reversion pull if VWAP extended
        norm_mom = mom / 1.0  # clamp [-1.0, 1.0]
        norm_v_dev = -v_dev / 25.0  # counter-trend pull if extended

        raw_direction = 0.60 * norm_mom + 0.40 * norm_v_dev
        direction = max(-1.0, min(1.0, raw_direction))

        # Conviction higher when momentum is clear and volatility is not extreme
        vol_damping = 1.0 if vol_ratio <= 2.0 else max(0.2, 2.0 / vol_ratio)
        raw_conviction = (0.50 * abs(norm_mom) + 0.50 * min(1.0, abs(v_dev) / 20.0)) * vol_damping
        conviction = max(0.0, min(1.0, raw_conviction))

        features = {
            "vwap_deviation_bps": v_dev,
            "short_momentum_pct": mom,
            "volatility_ratio": vol_ratio,
            "vol_damping": vol_damping,
        }
        return HorizonSignal(
            horizon=AlphaHorizon.SHORT_1M_5M,
            symbol=symbol,
            timestamp_ms=timestamp_ms,
            direction=direction,
            conviction=conviction,
            raw_score=raw_direction,
            features=features,
        )

    def extract_medium_signal(
        self,
        symbol: str,
        timestamp_ms: int,
        donchian_channel_pos: float,  # Position in Donchian Channel [-1.0, 1.0]
        trend_slope_bps: float,  # 15m-1h linear regression slope in bps [-30.0, 30.0]
        adx_trend_strength: float,  # Trend strength [0.0, 100.0]
    ) -> HorizonSignal:
        """Extract medium-horizon alpha (15m-1h) based on Donchian breakout and trend slope."""
        dc_pos = max(-1.0, min(1.0, donchian_channel_pos))
        slope = max(-30.0, min(30.0, trend_slope_bps))
        adx = max(0.0, min(100.0, adx_trend_strength))

        norm_slope = slope / 15.0
        raw_direction = 0.55 * dc_pos + 0.45 * norm_slope
        direction = max(-1.0, min(1.0, raw_direction))

        # Higher conviction if ADX confirms strong structural trend
        adx_factor = min(1.0, adx / 35.0)
        raw_conviction = (0.60 * abs(dc_pos) + 0.40 * min(1.0, abs(slope) / 10.0)) * max(
            0.3, adx_factor
        )
        conviction = max(0.0, min(1.0, raw_conviction))

        features = {
            "donchian_channel_pos": dc_pos,
            "trend_slope_bps": slope,
            "adx_trend_strength": adx,
            "adx_factor": adx_factor,
        }
        return HorizonSignal(
            horizon=AlphaHorizon.MEDIUM_15M_1H,
            symbol=symbol,
            timestamp_ms=timestamp_ms,
            direction=direction,
            conviction=conviction,
            raw_score=raw_direction,
            features=features,
        )


class MetaPolicyBlendingEngine:
    """Blends multi-horizon signals into composite execution decisions with conflict resolution."""

    def __init__(
        self,
        conflict_threshold: float = -0.05,
        conflict_penalty: float = 0.40,
        min_conviction_threshold: float = 0.20,
        min_direction_threshold: float = 0.10,
    ) -> None:
        self.conflict_threshold = conflict_threshold
        self.conflict_penalty = conflict_penalty
        self.min_conviction_threshold = min_conviction_threshold
        self.min_direction_threshold = min_direction_threshold

    def get_regime_weights(
        self, regime: MarketRegime, regime_confidence: float = 1.0
    ) -> EnsembleWeights:
        """Retrieve baseline horizon weights conditioned on market regime."""
        weights = REGIME_HORIZON_WEIGHTS.get(
            regime, REGIME_HORIZON_WEIGHTS[MarketRegime.CALM_BALANCED]
        )
        return EnsembleWeights(
            micro_weight=weights[0],
            short_weight=weights[1],
            medium_weight=weights[2],
            regime=regime,
            regime_confidence=max(0.0, min(1.0, regime_confidence)),
        )

    def blend(
        self,
        symbol: str,
        timestamp_ms: int,
        regime: MarketRegime,
        signals: dict[str, HorizonSignal],
        regime_confidence: float = 1.0,
    ) -> BlendedEnsembleDecision:
        """Blend horizon signals into an actionable decision with conflict shading."""
        weights = self.get_regime_weights(regime, regime_confidence)

        # Fail-closed defense lockout under toxic turbulence or zero weights
        if regime == MarketRegime.TOXIC_TURBULENCE or weights.weights_sum == 0.0:
            return BlendedEnsembleDecision(
                symbol=symbol,
                timestamp_ms=timestamp_ms,
                regime=regime,
                weights=weights,
                signals=signals,
                raw_blended_direction=0.0,
                raw_blended_conviction=0.0,
                conflict_detected=False,
                conflict_penalty=0.0,
                effective_direction=0.0,
                effective_conviction=0.0,
                target_action="DEFENSIVE_SUPPRESSED",
                target_micro_chunk_usdt=0.0,
                ensemble_state=EnsembleState.DEFENSE_LOCKOUT,
                notes="Regime TOXIC_TURBULENCE triggered emergency defense lockout.",
            )

        micro_sig = signals.get(str(AlphaHorizon.MICRO_1S_5S))
        short_sig = signals.get(str(AlphaHorizon.SHORT_1M_5M))
        med_sig = signals.get(str(AlphaHorizon.MEDIUM_15M_1H))

        d_micro = micro_sig.direction if micro_sig else 0.0
        c_micro = micro_sig.conviction if micro_sig else 0.0

        d_short = short_sig.direction if short_sig else 0.0
        c_short = short_sig.conviction if short_sig else 0.0

        d_med = med_sig.direction if med_sig else 0.0
        c_med = med_sig.conviction if med_sig else 0.0

        # Weighted combination
        raw_blended_direction = (
            weights.micro_weight * d_micro
            + weights.short_weight * d_short
            + weights.medium_weight * d_med
        )
        raw_blended_conviction = (
            weights.micro_weight * c_micro
            + weights.short_weight * c_short
            + weights.medium_weight * c_med
        )

        # 3. Detect Horizon Conflict between micro (fast orderbook) and medium (structural trend)
        # If micro and medium point in strongly opposite directions, conflict penalty engages
        horizon_cross_product = d_micro * d_med
        conflict_detected = bool(horizon_cross_product < self.conflict_threshold)

        penalty = self.conflict_penalty if conflict_detected else 1.0
        effective_direction = max(-1.0, min(1.0, raw_blended_direction * penalty))
        effective_conviction = max(0.0, min(1.0, raw_blended_conviction * penalty))

        # Determine target action and child order chunk size
        if (
            effective_conviction < self.min_conviction_threshold
            or abs(effective_direction) < self.min_direction_threshold
        ):
            target_action = "HOLD"
            chunk_usdt = 0.0
        elif effective_direction > 0.0:
            target_action = "BUY"
            raw_chunk = Decimal(str(5.00 * effective_conviction * abs(effective_direction)))
            chunk_usdt = float(
                max(Decimal("1.00"), min(Decimal("5.00"), raw_chunk)).quantize(
                    Decimal("0.01"), rounding=ROUND_DOWN
                )
            )
        else:
            target_action = "SELL"
            raw_chunk = Decimal(str(5.00 * effective_conviction * abs(effective_direction)))
            chunk_usdt = float(
                max(Decimal("1.00"), min(Decimal("5.00"), raw_chunk)).quantize(
                    Decimal("0.01"), rounding=ROUND_DOWN
                )
            )

        ensemble_state = (
            EnsembleState.CONFLICT_SHADED if conflict_detected else EnsembleState.ENSEMBLE_ACTIVE
        )
        notes = (
            f"Cross-product: {round(horizon_cross_product, 4)}, "
            f"Conflict penalty: {round(penalty, 2)}, "
            f"Effective conviction: {round(effective_conviction, 4)}"
        )

        return BlendedEnsembleDecision(
            symbol=symbol,
            timestamp_ms=timestamp_ms,
            regime=regime,
            weights=weights,
            signals=signals,
            raw_blended_direction=raw_blended_direction,
            raw_blended_conviction=raw_blended_conviction,
            conflict_detected=conflict_detected,
            conflict_penalty=penalty,
            effective_direction=effective_direction,
            effective_conviction=effective_conviction,
            target_action=target_action,
            target_micro_chunk_usdt=chunk_usdt,
            ensemble_state=ensemble_state,
            notes=notes,
        )


class CentralizedSolvencyLedger:
    """Double-entry solvency governance verifying zero-drift balance (|drift| < 1e-15 USDT)."""

    def __init__(self, starting_equity_usdt: float = 100.0) -> None:
        self.starting_equity = Decimal(str(starting_equity_usdt))
        self.cash = Decimal(str(starting_equity_usdt))
        self.allocated_margin = Decimal("0.0")
        self.unrealized_pnl = Decimal("0.0")
        self.realized_pnl = Decimal("0.0")
        self.total_fees = Decimal("0.0")
        self.total_slippage = Decimal("0.0")

    def apply_execution(
        self,
        margin_allocated: float,
        fee_usdt: float,
        slippage_usdt: float,
        unrealized_pnl_delta: float,
        realized_pnl_delta: float = 0.0,
    ) -> None:
        """Update double-entry ledger state with fee, slippage, and PnL increments."""
        m = Decimal(str(margin_allocated))
        f = Decimal(str(fee_usdt))
        s = Decimal(str(slippage_usdt))
        u = Decimal(str(unrealized_pnl_delta))
        r = Decimal(str(realized_pnl_delta))

        self.cash += r - (m + f + s)
        self.allocated_margin += m
        self.total_fees += f
        self.total_slippage += s
        self.unrealized_pnl += u
        self.realized_pnl += r

    @property
    def total_assets(self) -> Decimal:
        return self.cash + self.allocated_margin + self.unrealized_pnl

    @property
    def total_equity(self) -> Decimal:
        return (
            self.starting_equity
            + self.realized_pnl
            + self.unrealized_pnl
            - self.total_fees
            - self.total_slippage
        )

    def compute_drift(self) -> float:
        """Compute exact double-entry balance drift (|Assets - Equity|)."""
        return float(abs(self.total_assets - self.total_equity))

    def get_summary(self) -> dict[str, Any]:
        """Produce structured double-entry solvency summary."""
        drift = self.compute_drift()
        total_equity_val = float(self.total_equity)
        cash_val = float(self.cash)
        start_val = float(self.starting_equity)
        cash_reserve_pct = (cash_val / start_val) * 100.0 if start_val > 0 else 100.0
        return {
            "starting_equity_usdt": start_val,
            "cash_usdt": cash_val,
            "allocated_margin_usdt": float(self.allocated_margin),
            "unrealized_pnl_usdt": float(self.unrealized_pnl),
            "realized_pnl_usdt": float(self.realized_pnl),
            "total_equity_usdt": total_equity_val,
            "total_fees_usdt": float(self.total_fees),
            "total_slippage_usdt": float(self.total_slippage),
            "drift_usdt": drift,
            "zero_balance_drift_verified": drift < 1e-15,
            "tolerance_ceiling_usdt": 1e-15,
            "solvency_ratio_pct": round((total_equity_val / start_val) * 100.0, 4)
            if start_val > 0
            else 100.0,
            "cash_reserve_pct": round(cash_reserve_pct, 4),
            "unencumbered_cash_verified": cash_reserve_pct >= 40.0,
        }


